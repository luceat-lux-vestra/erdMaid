DROP TABLE IF EXISTS PURCHASE_ORDER;
DROP TABLE IF EXISTS CUSTOMER_ACCOUNT;

CREATE TABLE CUSTOMER_ACCOUNT (
    TENANT_ID BIGINT NOT NULL,
    ACCOUNT_ID BIGINT NOT NULL,
    DISPLAY_NAME VARCHAR(120) NOT NULL,
    EXTERNAL_REF VARCHAR(64),
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT PK_CUSTOMER_ACCOUNT PRIMARY KEY (TENANT_ID, ACCOUNT_ID),
    CONSTRAINT UK_CUSTOMER_ACCOUNT_EXTERNAL UNIQUE (TENANT_ID, EXTERNAL_REF)
);

COMMENT ON TABLE CUSTOMER_ACCOUNT IS 'Customer account fixture';
COMMENT ON COLUMN CUSTOMER_ACCOUNT.DISPLAY_NAME IS 'Display name shown to users';
COMMENT ON COLUMN CUSTOMER_ACCOUNT.EXTERNAL_REF IS 'Optional external reference';

CREATE TABLE PURCHASE_ORDER (
    TENANT_ID BIGINT NOT NULL,
    ORDER_ID BIGINT NOT NULL,
    ACCOUNT_ID BIGINT NOT NULL,
    AMOUNT DECIMAL(18, 2) NOT NULL,
    MEMO VARCHAR(255),
    CREATED_AT TIMESTAMP NOT NULL,
    CONSTRAINT PK_PURCHASE_ORDER PRIMARY KEY (TENANT_ID, ORDER_ID),
    CONSTRAINT FK_PURCHASE_ORDER_ACCOUNT
        FOREIGN KEY (TENANT_ID, ACCOUNT_ID)
        REFERENCES CUSTOMER_ACCOUNT (TENANT_ID, ACCOUNT_ID)
);

COMMENT ON TABLE PURCHASE_ORDER IS 'Purchase order fixture';
COMMENT ON COLUMN PURCHASE_ORDER.AMOUNT IS 'Order amount';
COMMENT ON COLUMN PURCHASE_ORDER.MEMO IS 'Optional memo';

